let current = 'zh-TW';

export function setLang(lang) {
  current = S[lang] ? lang : 'zh-TW';
  document.documentElement.lang = current;
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  let s = S[current][key] ?? S.en[key] ?? key;
  if (vars && typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export function regionName(code) {
  return REGIONS[code]?.[current] || REGIONS[code]?.en || code;
}

/** Localized country name for an ISO code (e.g. VN → 越南), via Intl. */
export function countryName(code) {
  try {
    const loc = { 'zh-TW': 'zh-Hant-TW', en: 'en', ko: 'ko' }[current] || 'zh-Hant-TW';
    return new Intl.DisplayNames([loc], { type: 'region' }).of(String(code).toUpperCase()) || code;
  } catch {
    return code;
  }
}
